package Loop;

public class forLoop {
    public static void main(String[] args) {
        for (int i =1;i<=6;i++){
            System.out.println("The value of i is this time " +i);
        }
        System.out.println("now lets come on second example");
        for (int j = 1; j<=14; j+=2){
            System.out.println("it's time to get the value of J "+j);
        }
    }
}
